_NUM_ADJECTIVES = len(ADJECTIVES)
_NUM_NOUNS = len(NOUNS)


def generate_name(*, rng: random.Random | None = None) -> str:
    """Generate a human-readable name like 'gallivanting-groundhog'.

    Args:
        rng: Optional Random instance for reproducible generation.
             If None, uses the module-level random state.

    Returns:
        A hyphenated adjective-noun pair.
    """
    r = rng or random
    adjective = r.choice(ADJECTIVES)
    noun = r.choice(NOUNS)
    return f'{adjective}-{noun}'


def generate_unique_names(n: int, *, rng: random.Random | None = None) -> list[str]:
    """Generate *n* unique human-readable names.

    Args:
        n: Number of unique names to generate.
        rng: Optional Random instance for reproducible generation.

    Returns:
        A list of *n* unique hyphenated adjective-noun pairs.

    Raises:
        ValueError: If *n* exceeds the total number of possible combinations.
    """
    max_combinations = _NUM_ADJECTIVES * _NUM_NOUNS
    if n > max_combinations:
        raise ValueError(
            f'Requested {n} unique names but only {max_combinations} '
            f'combinations exist ({_NUM_ADJECTIVES} adjectives x {_NUM_NOUNS} nouns)'
        )
    r = rng or random
    names: dict[str, None] = {}
    while len(names) < n:
        names[generate_name(rng=r)] = None
    return list(names)
